"""Local metadata cleanup removes AI provenance markers without changing pixels."""

import io
import struct
import zlib
from pathlib import Path

from PIL import Image, PngImagePlugin

from imagen_cli.application import operator_catalog as catalog
from imagen_cli.application.postprocess_service import render

MARKER = "AI-generated by test"


def _png_with_metadata(path: Path) -> Image.Image:
    image = Image.new("RGB", (16, 12), (12, 34, 56))
    exif = Image.Exif()
    exif[0x013B] = MARKER  # Artist
    exif[0x010E] = "prompt: hidden"  # ImageDescription
    info = PngImagePlugin.PngInfo()
    info.add_text("Software", MARKER)
    info.add_text("prompt", "a secret prompt")
    info.add_itxt("XML:com.adobe.xmp", f"<x:xmpmeta>{MARKER}</x:xmpmeta>")
    info.add_text("AIGC", '{"Label": "AI-generated"}')
    image.save(path, pnginfo=info, exif=exif.tobytes())

    payload = MARKER.encode()
    chunk = (
        struct.pack(">I", len(payload))
        + b"caBX"
        + payload
        + struct.pack(">I", zlib.crc32(b"caBX" + payload) & 0xFFFFFFFF)
    )
    data = path.read_bytes()
    end = data.rindex(b"IEND") - 4
    path.write_bytes(data[:end] + chunk + data[end:])
    return image


def test_purify_removes_png_provenance_and_keeps_pixels(tmp_path):
    source = tmp_path / "source.png"
    original = _png_with_metadata(source)
    assert MARKER.encode() in source.read_bytes()

    data, _ = render(source, [{"op": "strip_metadata", "params": {}}])

    assert MARKER.encode() not in data
    assert b"caBX" not in data
    assert b"xmpmeta" not in data
    with Image.open(io.BytesIO(data)) as output:
        assert output.size == original.size
        assert len(output.getexif()) == 0
        assert "Software" not in output.info
        assert output.tobytes() == original.tobytes()


def test_purify_removes_jpeg_exif_and_xmp(tmp_path):
    source = tmp_path / "source.jpg"
    exif = Image.Exif()
    exif[0x013B] = MARKER
    Image.new("RGB", (16, 12), (12, 34, 56)).save(
        source, format="JPEG", exif=exif.tobytes(),
        xmp=f"<x:xmpmeta>{MARKER}</x:xmpmeta>".encode(),
    )
    assert MARKER.encode() in source.read_bytes()

    data, _ = render(source, [{"op": "strip_metadata", "params": {}}])

    assert MARKER.encode() not in data
    with Image.open(io.BytesIO(data)) as output:
        assert len(output.getexif()) == 0
        assert "xmp" not in output.info


def test_purify_applies_exif_orientation(tmp_path):
    source = tmp_path / "rotated.png"
    exif = Image.Exif()
    exif[0x0112] = 6  # Rotate 90° clockwise.
    Image.new("RGB", (7, 3), "red").save(source, exif=exif.tobytes())

    data, _ = render(source, [{"op": "strip_metadata", "params": {}}])

    with Image.open(io.BytesIO(data)) as output:
        assert output.size == (3, 7)
        assert len(output.getexif()) == 0


def test_metadata_cleanup_is_a_listed_recipe_with_its_own_category():
    steps = catalog.PRESET_PIPELINES["元数据提纯"]
    assert [step["op"] for step in steps] == ["strip_metadata"]
    assert catalog.PRESET_CATEGORIES["元数据提纯"] == catalog.CATEGORIES["utility"]
    entry = next(
        item
        for item in catalog.browse_entries(include_aliases=True)
        if item["key"] == "元数据提纯"
    )
    assert entry["group"] == "实用工具"
    assert entry["name"] == "元数据提纯"
